"""
End-to-End Integration Tests for the complete HELIX-CORE Pipeline.
"""

import hashlib
from pathlib import Path
import unittest

from helix_core.ingestion import BinaryIngestor
from helix_core.pipeline import HelixPipeline


class TestHelixPipelineE2E(unittest.TestCase):
    """End-to-end pipeline validation with real files from disk."""

    def setUp(self):
        self.input_file = Path("test_sample.png").resolve()
        self.output_file = Path("recovered_test_sample.png").resolve()
        self.fasta_file = Path("synthesis_pool.fasta").resolve()
        self.pipeline = HelixPipeline(payload_size=28, parity_ratio=0.15)

    def tearDown(self):
        # Clean up temporary test output files
        if self.output_file.is_file():
            self.output_file.unlink()
        if self.fasta_file.is_file():
            self.fasta_file.unlink()

    def test_end_to_end_bit_perfect_reconstruction(self):
        """
        Verify the full 6-phase pipeline:
        1. Ingest actual PNG file from disk via open(..., 'rb').
        2. Convert to binary and fragment into fixed payloads.
        3. Generate Reed-Solomon parity chunks (15% redundancy).
        4. Enforce homopolymer <= 3 and GC 40-60% balancing.
        5. Assemble DNA strands with universal primers and export FASTA.
        6. Simulate 10% strand dropout during physical pool sequencing.
        7. Disassemble, validate CRC32, reconstruct with RS, reassemble file.
        8. Cryptographic SHA-256 comparison proves 100% bit-perfect fidelity!
        """
        self.assertTrue(self.input_file.is_file())
        orig_sha = BinaryIngestor.compute_sha256(self.input_file)

        stats = self.pipeline.run_full_cycle(
            input_filepath=self.input_file,
            output_filepath=self.output_file,
            fasta_export_path=self.fasta_file,
            drop_rate=0.10,      # 10% strand loss in liquid pool
            mutation_rate=0.00,  # Pure pool drop
        )

        # 1. Output file must exist on disk
        self.assertTrue(self.output_file.is_file())

        # 2. Strict bit-perfect validation: SHA-256 hashes MUST be identical
        rec_sha = BinaryIngestor.compute_sha256(self.output_file)
        self.assertEqual(rec_sha, orig_sha)
        self.assertTrue(stats.is_bit_perfect)

        # 3. Biophysical constraint compliance
        self.assertLessEqual(stats.max_homopolymer_observed, 3)
        self.assertGreaterEqual(stats.min_gc_content, 0.40)
        self.assertLessEqual(stats.max_gc_content, 0.60)
        self.assertEqual(stats.strand_length_bp, 184)  # 150-200 bp constraint satisfied

        # 4. FASTA export validation
        self.assertTrue(self.fasta_file.is_file())
        fasta_content = self.fasta_file.read_text(encoding="utf-8")
        self.assertIn(">HELIX_", fasta_content)
        self.assertIn(self.pipeline.translator.forward_primer, fasta_content)

    def test_recovery_with_strand_mutations(self):
        """
        Verify that strands with simulated mutations (SNPs) are rejected by CRC32
        and successfully regenerated by Reed-Solomon parity chunks.
        """
        stats = self.pipeline.run_full_cycle(
            input_filepath=self.input_file,
            output_filepath=self.output_file,
            drop_rate=0.08,      # 8% drop
            mutation_rate=0.04,  # 4% corrupted by point mutations
        )

        self.assertTrue(self.output_file.is_file())
        orig_sha = BinaryIngestor.compute_sha256(self.input_file)
        rec_sha = BinaryIngestor.compute_sha256(self.output_file)
        self.assertEqual(rec_sha, orig_sha)
        self.assertTrue(stats.is_bit_perfect)


if __name__ == "__main__":
    unittest.main()

